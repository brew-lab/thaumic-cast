/**
 * Generates the design tokens from `tokens.table.ts`:
 * - `src/tokens.css`: primitives, semantic tokens (one `light-dark()` pair each), type,
 *   space, shape, motion and size tokens, and the `[data-density]` sets;
 * - `src/tokens.ts`: typed token names, the colour pairs as hex, the script timings and the
 *   chrome constants;
 * - `src/webkit-fallbacks.css`: the desktop-only repeat of every themed token, for engines
 *   without `light-dark()`.
 *
 * Usage: `bun run tokens` writes the files; `bun run tokens:check` exits 1 when the committed
 * files differ from what the table generates.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';
import { hexToOklchCss } from './oklch';
import {
  CHROME,
  COMPONENT_PAIRS,
  CONTAINER_BREAKPOINTS_REM,
  DENSITY,
  FLUID_RAMP,
  LADDERS,
  LADDER_STOPS,
  LIVE,
  SEEDED,
  PLAIN,
  SEMANTIC_COLORS,
  SHADOW_OVERLAY,
  SPACE_STEPS,
  STATUS_SETS,
  TIMINGS,
  TRACKING,
  TYPE_STEPS,
  type ThemedToken,
  type TokenGroup,
  type TokenValue,
} from './tokens.table';

const SRC = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const HEADER =
  'Generated by packages/ui/scripts/generate-tokens.ts from scripts/tokens.table.ts.\n' +
  ' * Do not edit by hand: change the table and run `bun run tokens`.';

const isThemed = (v: TokenValue): v is ThemedToken => typeof v === 'object';

/**
 * Writes one colour value as CSS: hex becomes OKLCH, anything else passes through.
 * @param value - Hex, `var(--…)` or raw CSS
 * @returns The CSS value
 */
function color(value: string): string {
  return /^#[0-9a-f]{6}$/i.test(value) ? hexToOklchCss(value) : value;
}

/**
 * Writes a token value for `tokens.css`.
 * @param value - The table value
 * @returns The CSS value, with `light-dark()` for a themed pair
 */
function cssValue(value: TokenValue): string {
  return isThemed(value) ? `light-dark(${color(value.light)}, ${color(value.dark)})` : color(value);
}

const rem = (px: number): string => `${Number((px / 16).toFixed(4))}rem`;

/**
 * Writes a fluid step: `clamp(min, base + k·cqi, max)` over the F-fluid ramp.
 * @param min - The size in px at or below the ramp's start
 * @param max - The size in px at or above the ramp's end
 * @returns A rem value when fixed, otherwise the clamp
 */
function fluid(min: number, max: number): string {
  if (min === max) return rem(min);
  const slope = (max - min) / (FLUID_RAMP.to - FLUID_RAMP.from);
  const base = Number(((min - FLUID_RAMP.from * slope) / 16).toFixed(4));
  const k = Number((slope * 100).toFixed(4));
  return `clamp(${rem(min)}, ${base}rem + ${k}cqi, ${rem(max)})`;
}

/**
 * The status sets as token groups: `--{set}-container`, `--on-{set}-container`, `--{set}-ink`,
 * and `--{set}-glyph` (the on-container colour in light, the ink in dark).
 * @returns The status token group
 */
function statusGroup(): TokenGroup {
  const tokens: Record<string, TokenValue> = {};
  for (const [set, v] of Object.entries(STATUS_SETS)) {
    tokens[`${set}-container`] = v.container;
    tokens[`on-${set}-container`] = v.on;
    tokens[`${set}-ink`] = v.ink;
    tokens[`${set}-glyph`] = { light: `var(--on-${set}-container)`, dark: `var(--${set}-ink)` };
  }
  return { title: 'T-colour: status sets (in light, glyphs take the on-container colour)', tokens };
}

/** The tone tokens a component reads, in the order a `[data-tone]` block maps them. */
export const TONE_TOKENS = [
  'tone-container',
  'on-tone-container',
  'tone-glyph',
  'tone-ink',
] as const;

/**
 * The `[data-tone]` blocks: one per status set, mapping the set onto the `--tone-*` tokens. A
 * component sets `data-tone` on the element that carries the tone and reads `--tone-*` only,
 * as one of two pairs: on its container (container, on-container, glyph) or on a surface (the
 * ink). They hold no theme pair, so webkit-fallbacks.css need not repeat them.
 * @returns The CSS rules
 */
function toneBlocks(): string {
  return Object.keys(STATUS_SETS)
    .map((set) => {
      const [container, on, glyph, ink] = TONE_TOKENS;
      return `  [data-tone='${set}'] {
    --${container}: var(--${set}-container);
    --${on}: var(--on-${set}-container);
    --${glyph}: var(--${set}-glyph);
    --${ink}: var(--${set}-ink);
  }`;
    })
    .join('\n\n');
}

/** The type tokens: sizes, line heights and Geist tracking.
 * @returns The type token group
 */
function typeGroup(): TokenGroup {
  const tokens: Record<string, TokenValue> = {};
  TYPE_STEPS.forEach((step, i) => {
    tokens[`text-${i + 1}`] = fluid(step.min, step.max);
  });
  tokens['text-4-fixed'] = rem(14);
  TYPE_STEPS.forEach((step, i) => {
    // Fixed steps carry a unitless ratio; from 14 px up the line box follows the size,
    // rounded to a 2 px grid (DESIGN.md T-type).
    tokens[`leading-${i + 1}`] = step.leading
      ? String(Number((step.leading / step.min).toFixed(4)))
      : 'round(nearest, 1em + 0.375rem, 0.125rem)';
  });
  TRACKING.forEach((t, i) => {
    tokens[`tracking-${i + 1}`] = t;
  });
  return { title: 'T-type: steps, line heights and Geist tracking', tokens };
}

/** The space tokens.
 * @returns The space token group
 */
function spaceGroup(): TokenGroup {
  const tokens: Record<string, TokenValue> = {};
  for (const step of SPACE_STEPS) tokens[`space-${step.name}`] = fluid(step.min, step.max);
  return { title: 'T-space: steps 1 to 4 are fixed control internals; 5 to 8 are fluid', tokens };
}

/** The primitive ladders.
 * @returns The primitive token group
 */
function primitiveGroup(): TokenGroup {
  const tokens: Record<string, TokenValue> = {};
  for (const [name, row] of Object.entries(LADDERS)) {
    row.forEach((hex, i) => {
      tokens[`${name}-${LADDER_STOPS[i]}`] = hex;
    });
  }
  return { title: 'T-colour: primitives (components never read these)', tokens };
}

/** The elevation token, assembled from its two layers.
 * @returns The elevation token group
 */
function shadowGroup(): TokenGroup {
  return {
    title: 'T-elev: the one shadow, for top-layer surfaces only',
    tokens: {
      'shadow-overlay': SHADOW_OVERLAY.map(
        (s) => `${s.geometry} light-dark(${s.color.light}, ${s.color.dark})`,
      ).join(', '),
    },
  };
}

/** Every `:root` group, in output order.
 * @returns The groups
 */
function rootGroups(): TokenGroup[] {
  return [
    primitiveGroup(),
    SEMANTIC_COLORS,
    statusGroup(),
    COMPONENT_PAIRS,
    LIVE,
    SEEDED,
    PLAIN[0],
    typeGroup(),
    spaceGroup(),
    ...PLAIN.slice(1),
    shadowGroup(),
  ];
}

const block = (
  groups: TokenGroup[],
  value: (v: TokenValue, name: string) => string | null,
): string =>
  groups
    .map((g) => {
      const lines = Object.entries(g.tokens)
        .map(([name, v]) => {
          const css = value(v, name);
          return css === null ? null : `  --${name}: ${css};`;
        })
        .filter(Boolean);
      return lines.length ? `  /* ${g.title} */\n${lines.join('\n')}` : '';
    })
    .filter(Boolean)
    .join('\n\n');

/** Renders `tokens.css`.
 * @returns The file's contents
 */
function renderCss(): string {
  const density = (key: 'popup' | 'desktop'): string =>
    Object.entries(DENSITY)
      .map(([name, v]) => `    --${name}: ${v[key]};`)
      .join('\n');
  const coarse = (): string =>
    Object.entries(DENSITY)
      .filter(([, v]) => v.coarse)
      .map(([name, v]) => `      --${name}: ${v.coarse};`)
      .join('\n');
  return `/*
 * ${HEADER}
 */

/* T-state: the state layer, registered so it transitions instead of snapping. */
@property --layer {
  syntax: '<percentage>';
  inherits: false;
  initial-value: 0%;
}

/*
 * T-motion: the colours a change of state cross-fades (a segment's choice, a Button's
 * failed fill), registered so they transition instead of snapping. Where registration is
 * missing they switch at once.
 */
${['seg-bg', 'seg-fg', 'btn-bg', 'btn-fg']
  .map(
    (n) =>
      `@property --${n} {\n  syntax: '<color>';\n  inherits: true;\n  initial-value: transparent;\n}`,
  )
  .join('\n\n')}

/* T-colour: the live gradient's hue drift, in degrees. */
@property --live-shift {
  syntax: '<number>';
  inherits: true;
  initial-value: 0;
}

@layer tokens {
  :root {
${block(rootGroups(), cssValue).replace(/^/gm, '  ')}
  }

  /*
   * T-colour: the tones. Components never read a status set by name; they set data-tone and
   * read --tone-container, --on-tone-container and --tone-glyph (on the container) or
   * --tone-ink (on a surface).
   */
${toneBlocks()}

  /* T-target and T-size: [data-density] sets control heights; container queries never do. */
  :root,
  [data-density='popup'] {
${density('popup')}
  }

  [data-density='desktop'] {
${density('desktop')}
  }

  /* F-size: under touch the popup's hit floor rises to the window's; nothing drawn changes. */
  @media (any-pointer: coarse) {
    :root,
    [data-density='popup'] {
${coarse()}
    }
  }

  /* T-focus: Increase Contrast (macOS) raises the hairlines to the control edge. */
  @media (prefers-contrast: more) {
    :root {
      --outline-variant: var(--outline);
    }
  }
}
`;
}

/** The tokens a top-layer ::backdrop reads (the Dialog's scrim). */
const BACKDROP_TOKENS = ['scrim'];

/** Renders `webkit-fallbacks.css`: every themed token, per theme, for engines without light-dark().
 * @returns The file's contents
 */
function renderFallbacks(): string {
  const groups = rootGroups();
  const side = (key: 'light' | 'dark'): string =>
    block(groups, (v, name) => {
      if (isThemed(v)) return color(v[key]);
      if (name === 'shadow-overlay') {
        return SHADOW_OVERLAY.map((s) => `${s.geometry} ${s.color[key]}`).join(', ');
      }
      return null;
    }).replace(/^/gm, '    ');
  // Before Safari 17.4, ::backdrop inherits nothing, so the tokens a backdrop reads are set on
  // it too. Every engine that has light-dark() inherits into ::backdrop, so tokens.css needs
  // no such rule.
  const backdrop = (key: 'light' | 'dark'): string =>
    block(groups, (v, name) =>
      BACKDROP_TOKENS.includes(name) && isThemed(v) ? color(v[key]) : null,
    )
      .split('\n')
      .filter((l) => !l.includes('/*'))
      .map((l) => `    ${l}`)
      .join('\n');
  return `/*
 * ${HEADER}
 *
 * Desktop only. The desktop's floor is the system WebKit on macOS 13 with Safari 16.4 and
 * WebKitGTK 2.44, which have no light-dark(). This file repeats every themed token per theme,
 * the component pairs included, so no module writes light-dark() (check-ds rejects it).
 * Import it after tokens.css; the extension (Chrome 125) never loads it.
 */

@layer tokens {
  @supports not (color: light-dark(oklch(0% 0 0), oklch(100% 0 0))) {
    :root {
${side('light')}
    }

    @media (prefers-color-scheme: dark) {
      :root:not([data-theme='light']) {
${side('dark').replace(/^/gm, '  ')}
      }
    }

    :root[data-theme='dark'] {
${side('dark')}
    }

    ::backdrop {
${backdrop('light')}
    }

    @media (prefers-color-scheme: dark) {
      :root:not([data-theme='light']) ::backdrop {
${backdrop('dark').replace(/^/gm, '  ')}
      }
    }

    :root[data-theme='dark'] ::backdrop {
${backdrop('dark')}
    }

    @media (prefers-contrast: more) {
      :root {
        --outline-variant: var(--outline);
      }
    }
  }
}
`;
}

/** Renders `tokens.ts`.
 * @returns The file's contents
 */
function renderTs(): string {
  const names: string[] = [];
  const colors: Record<string, { light: string; dark: string }> = {};
  for (const g of rootGroups()) {
    for (const [name, v] of Object.entries(g.tokens)) {
      names.push(`--${name}`);
      if (isThemed(v) && v.light.startsWith('#') && v.dark.startsWith('#')) {
        colors[name] = { light: v.light, dark: v.dark };
      }
    }
  }
  names.push(...TONE_TOKENS.map((n) => `--${n}`));
  names.push(...Object.keys(DENSITY).map((n) => `--${n}`));
  const timings = Object.entries(TIMINGS)
    .map(
      ([k, v]) =>
        `/** DESIGN.md T-motion: a timing used from script, in ms. */\nexport const ${k} = ${v};`,
    )
    .join('\n\n');
  return `/*
 * ${HEADER}
 */

/** Every token name defined in tokens.css. */
export const TOKEN_NAMES = ${JSON.stringify(names)} as const;

/** A design token name, with its leading \`--\`. */
export type TokenName = (typeof TOKEN_NAMES)[number];

/** The themed colour tokens as hex, for script that draws outside CSS (names without \`--\`). */
export const COLORS = ${JSON.stringify(colors)} as const;

/** A themed colour token name (without \`--\`). */
export type ColorName = keyof typeof COLORS;

${timings}

/** Container-query breakpoints in rem: the only literals allowed in \`@container\` (F-grid). */
export const CONTAINER_BREAKPOINTS_REM = ${JSON.stringify(CONTAINER_BREAKPOINTS_REM)} as const;

/** Colours and assets that Chrome and the OS draw, outside CSS (DESIGN.md T-chrome). */
export const CHROME = {
  /** chrome.action badge: the text is "!" only, never a count. */
  toolbarBadge: ${JSON.stringify(CHROME.toolbarBadge)},
  /** Tray icon: mark 1b idle, filled (lit) while any cast plays; one file per OS theme. */
  tray: ${JSON.stringify(CHROME.tray)},
} as const;
`;
}

/**
 * Renders every generated file, formatted with the repo's Prettier config.
 * @returns A map of absolute file path to contents
 */
export async function renderTokens(): Promise<Record<string, string>> {
  const files: Record<string, string> = {
    [join(SRC, 'tokens.css')]: renderCss(),
    [join(SRC, 'webkit-fallbacks.css')]: renderFallbacks(),
    [join(SRC, 'tokens.ts')]: renderTs(),
  };
  for (const [path, text] of Object.entries(files)) {
    files[path] = await format(text, {
      filepath: path,
      printWidth: 100,
      singleQuote: true,
      trailingComma: 'all',
      tabWidth: 2,
    });
  }
  return files;
}

/** Writes the files, or with `--check` reports any that are out of date. */
async function main(): Promise<void> {
  const check = process.argv.includes('--check');
  const files = await renderTokens();
  const stale: string[] = [];
  for (const [path, text] of Object.entries(files)) {
    if (check) {
      const current = await readFile(path, 'utf8').catch(() => '');
      if (current !== text) stale.push(path);
    } else {
      await writeFile(path, text);
    }
  }
  if (check && stale.length) {
    process.stderr.write(
      `Design tokens are out of date. Run \`bun run tokens\` and commit:\n${stale.map((p) => `  ${p}`).join('\n')}\n`,
    );
    process.exit(1);
  }
  process.stdout.write(check ? 'Design tokens are up to date.\n' : 'Design tokens written.\n');
}

if (import.meta.main) await main();
